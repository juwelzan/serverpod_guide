'use client';

import React, { useState } from 'react';
import { Header } from '@/components/layout/Header';
import { Footer } from '@/components/layout/Footer';
import { Sparkles, Terminal, Code2, Database, Play, Check, Copy } from 'lucide-react';

export default function PlaygroundPage() {
  const [activeTab, setActiveTab] = useState<'endpoint' | 'yaml' | 'cli'>('endpoint');

  // Endpoint simulator states
  const [selectedEndpoint, setSelectedEndpoint] = useState<'greeting' | 'createTask' | 'getTasks'>('greeting');
  const [inputParam, setInputParam] = useState('Juwel');
  const [endpointResponse, setEndpointResponse] = useState<string | null>(null);
  const [isLoading, setIsLoading] = useState(false);

  // YAML simulator state
  const [yamlInput, setYamlInput] = useState(`class: Product
table: product
fields:
  title: String
  price: double
  inStock: bool
  description: String?`);

  // CLI command generator state
  const [projectName, setProjectName] = useState('my_super_app');
  const [includeAuth, setIncludeAuth] = useState(true);
  const [copiedCmd, setCopiedCmd] = useState(false);

  const runEndpointTest = () => {
    setIsLoading(true);
    setEndpointResponse(null);

    setTimeout(() => {
      setIsLoading(false);
      if (selectedEndpoint === 'greeting') {
        setEndpointResponse(
          JSON.stringify(
            {
              status: 200,
              type: 'String',
              data: `হ্যালো, ${inputParam || 'বন্ধু'}! Serverpod RPC কল সফল হয়েছে।`,
              serverLatency: '14ms',
              protocol: 'Serverpod Type-Safe RPC',
            },
            null,
            2
          )
        );
      } else if (selectedEndpoint === 'createTask') {
        setEndpointResponse(
          JSON.stringify(
            {
              status: 201,
              type: 'Task',
              data: {
                id: Math.floor(Math.random() * 100) + 1,
                title: inputParam || 'নতুন টাস্ক',
                isCompleted: false,
                createdAt: new Date().toISOString(),
              },
              serverLatency: '22ms',
            },
            null,
            2
          )
        );
      } else {
        setEndpointResponse(
          JSON.stringify(
            {
              status: 200,
              type: 'List<Task>',
              data: [
                { id: 1, title: 'Serverpod ইনস্টল করা', isCompleted: true },
                { id: 2, title: 'ডাটাবেস মাইগ্রেশন সম্পন্ন করা', isCompleted: false },
              ],
              serverLatency: '18ms',
            },
            null,
            2
          )
        );
      }
    }, 400);
  };

  const getGeneratedDartCode = () => {
    return `// Auto-generated by Serverpod Generator
// DO NOT EDIT MANUALLY!

class Product extends SerializableModel {
  int? id;
  String title;
  double price;
  bool inStock;
  String? description;

  Product({
    this.id,
    required this.title,
    required this.price,
    required this.inStock,
    this.description,
  });

  @override
  Map<String, dynamic> toJson() => {
    'id': id,
    'title': title,
    'price': price,
    'inStock': inStock,
    'description': description,
  };
}`;
  };

  const getGeneratedSqlMigration = () => {
    return `-- Generated PostgreSQL Table Migration
CREATE TABLE "product" (
  "id" serial PRIMARY KEY,
  "title" text NOT NULL,
  "price" double precision NOT NULL,
  "inStock" boolean NOT NULL,
  "description" text
);`;
  };

  const generatedCliCmd = `serverpod create ${projectName || 'my_app'}
cd ${projectName || 'my_app'}_server
${includeAuth ? 'dart pub add serverpod_auth_server\n' : ''}serverpod generate
dart run bin/main.dart`;

  const copyCli = () => {
    navigator.clipboard.writeText(generatedCliCmd);
    setCopiedCmd(true);
    setTimeout(() => setCopiedCmd(false), 2000);
  };

  return (
    <div className="min-h-screen flex flex-col bg-slate-950 text-slate-100">
      <Header />

      <main className="flex-1 max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-10 w-full">
        {/* Page Title */}
        <div className="text-center max-w-2xl mx-auto mb-10">
          <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-indigo-500/10 border border-indigo-500/20 text-indigo-400 text-xs font-semibold mb-3">
            <Sparkles className="w-3.5 h-3.5" />
            <span>ইন্টারেক্টিভ লার্নিং ল্যাব</span>
          </div>
          <h1 className="text-2xl sm:text-4xl font-extrabold tracking-tight">
            Serverpod <span className="text-indigo-400">প্লে-গ্রাউন্ড</span>
          </h1>
          <p className="mt-2 text-sm text-slate-400">
            ব্রাউজারেই সার্ভারপড এন্ডপয়েন্ট টেস্ট, YAML মডেল জেনারেশন এবং কমান্ড পরখ করুন।
          </p>
        </div>

        {/* Tab Switcher */}
        <div className="flex justify-center mb-8">
          <div className="inline-flex p-1 rounded-xl bg-slate-900 border border-slate-800 gap-1">
            <button
              onClick={() => setActiveTab('endpoint')}
              className={`flex items-center gap-2 px-4 py-2 rounded-lg text-xs sm:text-sm font-semibold transition ${
                activeTab === 'endpoint'
                  ? 'bg-indigo-600 text-white shadow-md'
                  : 'text-slate-400 hover:text-slate-200'
              }`}
            >
              <Play className="w-4 h-4" />
              <span>RPC Endpoint সিমুলেটর</span>
            </button>

            <button
              onClick={() => setActiveTab('yaml')}
              className={`flex items-center gap-2 px-4 py-2 rounded-lg text-xs sm:text-sm font-semibold transition ${
                activeTab === 'yaml'
                  ? 'bg-indigo-600 text-white shadow-md'
                  : 'text-slate-400 hover:text-slate-200'
              }`}
            >
              <Database className="w-4 h-4" />
              <span>YAML মডেল জেনারেটর</span>
            </button>

            <button
              onClick={() => setActiveTab('cli')}
              className={`flex items-center gap-2 px-4 py-2 rounded-lg text-xs sm:text-sm font-semibold transition ${
                activeTab === 'cli'
                  ? 'bg-indigo-600 text-white shadow-md'
                  : 'text-slate-400 hover:text-slate-200'
              }`}
            >
              <Terminal className="w-4 h-4" />
              <span>কমান্ড বিল্ডার</span>
            </button>
          </div>
        </div>

        {/* Tab 1: Endpoint Simulator */}
        {activeTab === 'endpoint' && (
          <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
            <div className="p-6 rounded-2xl border border-slate-800 bg-slate-900/60 space-y-5">
              <h3 className="text-base font-bold text-slate-100 flex items-center gap-2">
                <Code2 className="w-5 h-5 text-indigo-400" />
                <span>ক্লায়েন্ট কল কনফিগারেশন</span>
              </h3>

              <div>
                <label className="block text-xs font-semibold text-slate-300 mb-2">
                  এন্ডপয়েন্ট নির্বাচন করুন:
                </label>
                <div className="grid grid-cols-3 gap-2">
                  {[
                    { key: 'greeting', label: 'client.greeting.hello()' },
                    { key: 'createTask', label: 'client.task.createTask()' },
                    { key: 'getTasks', label: 'client.task.getTasks()' },
                  ].map((ep) => (
                    <button
                      key={ep.key}
                      onClick={() => setSelectedEndpoint(ep.key as 'greeting' | 'createTask' | 'getTasks')}
                      className={`p-2.5 rounded-xl border text-xs font-mono transition text-left ${
                        selectedEndpoint === ep.key
                          ? 'border-indigo-500 bg-indigo-500/10 text-indigo-300 font-semibold'
                          : 'border-slate-800 bg-slate-950/40 text-slate-400 hover:border-slate-700'
                      }`}
                    >
                      {ep.label}
                    </button>
                  ))}
                </div>
              </div>

              {selectedEndpoint !== 'getTasks' && (
                <div>
                  <label className="block text-xs font-semibold text-slate-300 mb-2">
                    প্যারামিটার ইনপুট:
                  </label>
                  <input
                    type="text"
                    value={inputParam}
                    onChange={(e) => setInputParam(e.target.value)}
                    placeholder="প্যারামিটার দিন..."
                    className="w-full px-3.5 py-2.5 rounded-xl bg-slate-950 border border-slate-800 text-sm text-slate-200 focus:outline-none focus:border-indigo-500"
                  />
                </div>
              )}

              <div className="p-3 rounded-xl bg-slate-950/80 border border-slate-800 text-xs font-mono text-indigo-300">
                <span className="text-slate-500">{'// Flutter কোড যা এক্সিকিউট হচ্ছে'}</span>
                <p className="mt-1">
                  {selectedEndpoint === 'greeting' &&
                    `final res = await client.greeting.hello("${inputParam || ''}");`}
                  {selectedEndpoint === 'createTask' &&
                    `final res = await client.task.createTask("${inputParam || ''}");`}
                  {selectedEndpoint === 'getTasks' &&
                    `final res = await client.task.getTasks();`}
                </p>
              </div>

              <button
                onClick={runEndpointTest}
                disabled={isLoading}
                className="w-full py-3 rounded-xl bg-indigo-600 hover:bg-indigo-500 disabled:opacity-50 text-white font-semibold text-sm transition shadow-lg shadow-indigo-600/25 flex items-center justify-center gap-2"
              >
                <Play className="w-4 h-4" />
                <span>{isLoading ? 'সার্ভার কল হচ্ছে...' : 'এন্ডপয়েন্ট কল করুন (Execute)'}</span>
              </button>
            </div>

            <div className="p-6 rounded-2xl border border-slate-800 bg-slate-900/60 flex flex-col">
              <h3 className="text-base font-bold text-slate-100 mb-4 flex items-center justify-between">
                <span>সার্ভার রেসপন্স (Type-Safe Result)</span>
                {endpointResponse && (
                  <span className="text-xs px-2.5 py-0.5 rounded-full bg-emerald-500/10 text-emerald-400 border border-emerald-500/20 font-mono">
                    200 OK
                  </span>
                )}
              </h3>

              <div className="flex-1 min-h-[220px] rounded-xl bg-slate-950 p-4 font-mono text-xs text-slate-300 border border-slate-800 overflow-x-auto flex items-center justify-center">
                {isLoading ? (
                  <div className="text-center text-slate-500 space-y-2">
                    <div className="w-6 h-6 border-2 border-indigo-500 border-t-transparent rounded-full animate-spin mx-auto" />
                    <p>সার্ভার সেশন ভ্যালিডেশন হচ্ছে...</p>
                  </div>
                ) : endpointResponse ? (
                  <pre className="w-full text-left">
                    <code>{endpointResponse}</code>
                  </pre>
                ) : (
                  <p className="text-slate-500 text-center">
                    বামপাশের "এন্ডপয়েন্ট কল করুন" বাটনে ক্লিক করে ফলাফল দেখুন।
                  </p>
                )}
              </div>
            </div>
          </div>
        )}

        {/* Tab 2: YAML Simulator */}
        {activeTab === 'yaml' && (
          <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
            <div className="p-6 rounded-2xl border border-slate-800 bg-slate-900/60 space-y-3">
              <h3 className="text-base font-bold text-slate-100 flex items-center gap-2">
                <Database className="w-5 h-5 text-indigo-400" />
                <span>lib/src/models/product.spy.yaml</span>
              </h3>
              <p className="text-xs text-slate-400">
                মডেলের YAML পরিবর্তন করুন এবং স্বয়ংক্রিয়ভাবে জেনারেট হওয়া Dart ক্লাস ও SQL স্কিমা দেখুন:
              </p>
              <textarea
                value={yamlInput}
                onChange={(e) => setYamlInput(e.target.value)}
                rows={9}
                className="w-full p-4 rounded-xl bg-slate-950 border border-slate-800 font-mono text-xs text-slate-200 focus:outline-none focus:border-indigo-500 leading-relaxed"
              />
            </div>

            <div className="space-y-4">
              <div className="p-5 rounded-2xl border border-slate-800 bg-slate-900/60">
                <h4 className="text-xs font-bold text-indigo-400 uppercase tracking-wider mb-2">
                  Generated Client Dart Class
                </h4>
                <div className="max-h-48 overflow-y-auto rounded-xl bg-slate-950 p-3 font-mono text-[11px] text-slate-300 border border-slate-800">
                  <pre>
                    <code>{getGeneratedDartCode()}</code>
                  </pre>
                </div>
              </div>

              <div className="p-5 rounded-2xl border border-slate-800 bg-slate-900/60">
                <h4 className="text-xs font-bold text-emerald-400 uppercase tracking-wider mb-2">
                  Generated PostgreSQL Table SQL
                </h4>
                <div className="rounded-xl bg-slate-950 p-3 font-mono text-[11px] text-slate-300 border border-slate-800">
                  <pre>
                    <code>{getGeneratedSqlMigration()}</code>
                  </pre>
                </div>
              </div>
            </div>
          </div>
        )}

        {/* Tab 3: CLI Command Generator */}
        {activeTab === 'cli' && (
          <div className="max-w-2xl mx-auto p-6 rounded-2xl border border-slate-800 bg-slate-900/60 space-y-5">
            <h3 className="text-base font-bold text-slate-100 flex items-center gap-2">
              <Terminal className="w-5 h-5 text-indigo-400" />
              <span>কমান্ড জেনারেটর</span>
            </h3>

            <div>
              <label className="block text-xs font-semibold text-slate-300 mb-1">
                প্রজেক্টের নাম (snake_case):
              </label>
              <input
                type="text"
                value={projectName}
                onChange={(e) => setProjectName(e.target.value.toLowerCase().replace(/[^a-z0-9_]/g, '_'))}
                className="w-full px-3.5 py-2.5 rounded-xl bg-slate-950 border border-slate-800 text-sm text-slate-200 focus:outline-none focus:border-indigo-500 font-mono"
              />
            </div>

            <div className="flex items-center gap-3">
              <input
                type="checkbox"
                id="authCheck"
                checked={includeAuth}
                onChange={(e) => setIncludeAuth(e.target.checked)}
                className="w-4 h-4 rounded text-indigo-600 bg-slate-950 border-slate-800"
              />
              <label htmlFor="authCheck" className="text-xs text-slate-300 cursor-pointer">
                Serverpod Auth মডিউল ডিপেন্ডেন্সি অন্তর্ভুক্ত করুন
              </label>
            </div>

            <div className="relative rounded-xl bg-slate-950 p-4 font-mono text-xs text-slate-200 border border-slate-800">
              <pre>
                <code>{generatedCliCmd}</code>
              </pre>
              <button
                onClick={copyCli}
                className="absolute top-3 right-3 flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-xs text-slate-200 border border-slate-700 transition"
              >
                {copiedCmd ? (
                  <>
                    <Check className="w-3.5 h-3.5 text-emerald-400" />
                    <span className="text-emerald-400">কপি হয়েছে!</span>
                  </>
                ) : (
                  <>
                    <Copy className="w-3.5 h-3.5" />
                    <span>কপি কমান্ড</span>
                  </>
                )}
              </button>
            </div>
          </div>
        )}
      </main>

      <Footer />
    </div>
  );
}
